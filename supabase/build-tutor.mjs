// Copies the pure tutor logic and the 70 PDF items into the Edge Function (single source of truth = app/).
//   node supabase/build-tutor.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'supabase', 'functions', 'tutor', 'lib');
mkdirSync(lib, { recursive: true });

const header = '// GENERATED by supabase/build-tutor.mjs — do not edit; edit app/src/… instead.\n';
writeFileSync(join(lib, 'tutor.js'), header + readFileSync(join(root, 'app', 'src', 'engine', 'tutor.js'), 'utf8'));

const cases = JSON.parse(readFileSync(join(root, 'app', 'src', 'content', 'cases.json'), 'utf8'));
const slim = cases.map((c) => ({
  id: c.id, title: c.title, form: c.form,
  items: c.items.map(({ id, kind, ind, label, prompt, options, answer, boxes, clue, step, steps }) =>
    ({ id, kind, ind, label, prompt, options, answer, boxes, clue, step, steps })),
}));
writeFileSync(join(lib, 'items.js'), `${header}export const CASES = ${JSON.stringify(slim)};\n`);
console.log(`Tutor lib written: ${slim.reduce((n, c) => n + c.items.length, 0)} items`);
