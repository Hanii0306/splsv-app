// Copies the pure tutor logic and the 4 PDF test soal into the Edge Function (single source of truth = app/).
//   node supabase/build-tutor.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'supabase', 'functions', 'tutor', 'lib');
mkdirSync(lib, { recursive: true });

const header = '// GENERATED by supabase/build-tutor.mjs — do not edit; edit app/src/… instead.\n';
writeFileSync(join(lib, 'tutor.js'), header + readFileSync(join(root, 'app', 'src', 'engine', 'tutor.js'), 'utf8'));

// v2.0: the only questions are the 4 soal of the PDF test (app/src/content/test.json).
const test = JSON.parse(readFileSync(join(root, 'app', 'src', 'content', 'test.json'), 'utf8'));
const slim = [{
  id: 'UJI', title: test.title, form: 'soal cerita',
  items: test.items.map(({ id, ind, title, stem, list, ask, tahap, clue, step, steps, keys }) =>
    ({ id, kind: 'essay', ind, label: title, stem, list, ask, tahap, clue, step, steps, keys })),
}];
writeFileSync(join(lib, 'items.js'), `${header}export const CASES = ${JSON.stringify(slim)};\n`);
console.log(`Tutor lib written: ${slim[0].items.length} soal`);
